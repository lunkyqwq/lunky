#!/usr/bin/env python3
"""Regenerate or verify the SHA-256 manifest for the source-only patch bundle."""
from hashlib import sha256
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "PATCH-BUNDLE-MANIFEST.sha256"
FILES = (
    ".github/workflows/verify-save-flow-patch.yml",
    "BUILD-READINESS-REPORT.md", "README-zh-CN.md", "README.md",
    "SAVE-FLOW-TEST-PLAN.md", "SOURCE-INTEGRATION-AUDIT.md", "SOURCE-SNAPSHOT-COMPARISON.md",
    "patches/save-flow-3.4.1/PATCH-NOTES.md",
    "patches/save-flow-3.4.1/ReflexAiClient.java",
    "patches/save-flow-3.4.1/apply-save-flow-patch.ps1",
    "tools/audit_local_source.py", "tools/audit_source_provenance.py",
    "tools/audit_source_archive.py", "tools/test_audit_source_archive.py",
    "tools/check_save_flow_patch.py", "tools/test_save_flow_checker.py",
    "tools/test_source_provenance_audit.py", "tools/test_verify_patch_bundle.py",
    "tools/update_patch_bundle_manifest.py", "tools/verify_patch_bundle.py",
)

def expected_text() -> str:
    lines = ["# SHA-256  relative/path; generated by tools/update_patch_bundle_manifest.py"]
    for name in sorted(FILES):
        path = ROOT / name
        if not path.is_file():
            raise FileNotFoundError(f"required manifest file missing: {name}")
        lines.append(f"{sha256(path.read_bytes()).hexdigest()}  {name}")
    return "\n".join(lines) + "\n"

def main() -> int:
    if len(sys.argv) > 2 or (len(sys.argv) == 2 and sys.argv[1] != "--check"):
        print("Usage: python3 tools/update_patch_bundle_manifest.py [--check]")
        return 2
    try:
        wanted = expected_text()
    except OSError as exc:
        print(f"FAIL: {exc}")
        return 1
    if len(sys.argv) == 2:
        current = MANIFEST.read_text(encoding="utf-8") if MANIFEST.is_file() else ""
        if current != wanted:
            print("FAIL: PATCH-BUNDLE-MANIFEST.sha256 is stale; run the script without --check")
            return 1
        print(f"PASS: manifest is current ({len(FILES)} files)")
        return 0
    MANIFEST.write_text(wanted, encoding="utf-8", newline="\n")
    print(f"UPDATED: {MANIFEST.name} ({len(FILES)} files)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
